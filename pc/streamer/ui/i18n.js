// ---------------------------------------------------------------- language choice
// Stored in localStorage next to "connectedBefore": a UI preference, not a
// streamer setting. "auto" follows the browser's languages.
const STORE_KEY = "language";
let current = "en";
let choice = "auto";

function normalize(tag) {
  const lower = String(tag).toLowerCase().replace("_", "-");
  if (lower.startsWith("zh")) {
    const traditional = /hant|tw|hk|mo/.test(lower);
    return traditional ? "zh-TW" : "zh-CN";
  }
  const base = lower.split("-")[0];
  return STRINGS[base] ? base : null;
}

// The best language for this browser, or "en" when nothing matches.
export function detectLanguage() {
  const candidates = navigator.languages || [navigator.language || "en"];
  for (const tag of candidates) {
    const match = normalize(tag);
    if (match) return match;
  }
  return "en";
}

function loadChoice() {
  try { return localStorage.getItem(STORE_KEY) || "auto"; } catch { return "auto"; }
}

// Applies the stored choice (or "auto") and returns the resolved code.
export function initLanguage() {
  choice = loadChoice();
  current = choice === "auto" ? detectLanguage() : normalize(choice) || "en";
  document.documentElement.lang = current;
  return current;
}

// Switches the UI language: "auto" or a code from LANGUAGES. Persists the
// choice; the caller applies the new strings to the page.
export function setLanguage(code) {
  choice = STRINGS[code] ? code : "auto";
  current = choice === "auto" ? detectLanguage() : choice;
  document.documentElement.lang = current;
  try { localStorage.setItem(STORE_KEY, choice); } catch {}
  return current;
}

export function getLanguage() { return current; }
export function getLanguageChoice() { return choice; }
// For Intl (dates): the resolved language always is a valid BCP 47 tag.
export function locale() { return current; }

// ---------------------------------------------------------------- lookup
// t("key", { name }) replaces {name} placeholders. Unknown keys return the key
// itself, so a typo is visible instead of silently empty.
export function t(key, params) {
  let s = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

// Applies translations to everything marked up in the HTML: data-i18n sets
// the element's text, data-i18n-aria its accessible name.
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
}
